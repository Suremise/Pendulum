<#
.SYNOPSIS
    Builds THIRD-PARTY-NOTICES.md from what Pendulum ships, or checks it's up to date.

.DESCRIPTION
    The packages come from the App's real dependency graph (dotnet list package
    --include-transitive) and the .NET runtime packs it publishes with; their licences, notes and
    the things that aren't packages (the installer, sounds, icons, downloads) come from
    scripts/third-party.json. Licence and notice texts are copied from each package's own files in
    the NuGet cache, or from scripts/licences/.

    It fails when a package that ships has no entry in third-party.json, when an entry names a
    package that no longer ships, or when a decision is still PENDING.

.PARAMETER Check
    Builds the notices in memory and fails if THIRD-PARTY-NOTICES.md differs. Writes nothing.

.EXAMPLE
    pwsh scripts/third-party-notices.ps1
    pwsh scripts/third-party-notices.ps1 -Check
#>
[CmdletBinding()]
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$app = Join-Path $repo 'Pendulum.App/Pendulum.App.csproj'
$inventoryPath = Join-Path $repo 'scripts/third-party.json'
$outputPath = Join-Path $repo 'THIRD-PARTY-NOTICES.md'
$nuget = if ($env:NUGET_PACKAGES) { $env:NUGET_PACKAGES } else { Join-Path $HOME '.nuget/packages' }

function Fail([string]$message) { Write-Error $message; exit 1 }

$inventory = Get-Content $inventoryPath -Raw | ConvertFrom-Json

# --- What ships: the App's packages and the runtime packs it publishes with -----------------------

$listing = & dotnet list $app package --include-transitive --format json 2>$null | Out-String
if ($LASTEXITCODE -ne 0) { Fail "dotnet list package failed: restore the solution first (dotnet restore Pendulum.sln)." }
$framework = (ConvertFrom-Json $listing).projects[0].frameworks[0]
$shipped = @($framework.topLevelPackages) + @($framework.transitivePackages) |
    ForEach-Object { [pscustomobject]@{ Id = $_.id; Version = $_.resolvedVersion } } |
    Sort-Object Id -Unique

$assets = Get-Content (Join-Path $repo 'Pendulum.App/obj/project.assets.json') -Raw | ConvertFrom-Json
$downloads = $assets.project.frameworks.PSObject.Properties | Select-Object -First 1 | ForEach-Object { $_.Value.downloadDependencies }
function RuntimePackVersion([string]$id) {
    $dep = $downloads | Where-Object name -eq $id | Select-Object -First 1
    if (-not $dep) { Fail "$id isn't among the App's runtime packs (is it still self-contained for win-x64?)." }
    $dep.version -replace '^\[([^,\]]+).*$', '$1'
}

# --- Every package has an entry, and every entry still ships ------------------------------------

$problems = @()
foreach ($p in $shipped) {
    $e = $inventory.packages | Where-Object id -eq $p.Id
    if (-not $e) { $problems += "Ships but isn't in third-party.json: $($p.Id) $($p.Version)" }
    elseif ($e.auditedVersion -and $e.auditedVersion -ne $p.Version) {
        $problems += "$($p.Id) is now $($p.Version), but its licence was checked for $($e.auditedVersion): check its native source ($($e.nativeSource)) again, then update licenceText and auditedVersion."
    }
}
foreach ($e in $inventory.packages) {
    if (-not ($shipped | Where-Object Id -eq $e.id)) { $problems += "In third-party.json but no longer ships: $($e.id)" }
}
foreach ($o in @($inventory.other) + @($inventory.downloads)) {
    if ("$($o.decision) $($o.licence) $($o.copyright)" -match 'PENDING') { $problems += "Waiting for a decision: $($o.name)" }
}
if ($problems) { Fail ("THIRD-PARTY-NOTICES can't be built:`n  " + ($problems -join "`n  ")) }

function PackageDir([string]$id, [string]$version) {
    $dir = Join-Path $nuget "$($id.ToLowerInvariant())/$version"
    if (-not (Test-Path $dir)) { Fail "$id $version isn't in the NuGet cache ($dir): restore the solution first." }
    $dir
}

function Copyright($entry, [string]$dir) {
    $nuspec = Get-ChildItem $dir -Filter *.nuspec | Select-Object -First 1
    $c = if ($nuspec) { ([xml](Get-Content $nuspec.FullName -Raw)).package.metadata.copyright } else { $null }
    if ($c) { ($c -replace '^\s*(Copyright\s*)?(\(c\)|©|\(C\))?\s*', '' -replace '\s*All rights reserved\.?\s*$', '').Trim().TrimEnd('.') } else { $entry.copyright }
}

function Text([string]$path) { (Get-Content $path -Raw) -replace "`r`n", "`n" -replace '\s+$', '' }

# --- The notices ---------------------------------------------------------------------------------

$nl = "`n"
$out = [System.Text.StringBuilder]::new()
function Line([string]$s = '') { [void]$out.Append($s + $nl) }

Line '# Third-party notices'
Line
Line 'Pendulum is MIT-licensed (see LICENSE). It is built on the open-source software below, all used unmodified.'
Line 'This file is generated by `scripts/third-party-notices.ps1` from `scripts/third-party.json` and the packages'
Line 'Pendulum is built from: edit those, not this.'
Line
Line '## What ships with Pendulum'
Line
Line '| Component | Version | Licence | Copyright | Notes |'
Line '|---|---|---|---|---|'

$rows = @()
$mitHolders = [System.Collections.Generic.List[string]]::new()
$noticeFiles = [ordered]@{}
$licenceFiles = [ordered]@{}
foreach ($p in $shipped) {
    $e = $inventory.packages | Where-Object id -eq $p.Id
    $dir = PackageDir $p.Id $p.Version
    $holder = Copyright $e $dir
    $notes = (@($e.note, $(if ($e.nativeSource) { "Native source: $($e.nativeSource)" })) | Where-Object { $_ }) -join ' '
    $rows += "| [$($p.Id)]($($e.url)) | $($p.Version) | $($e.licence) | $holder | $notes |"
    if ($e.licence -eq 'MIT' -and -not $e.licenceFile -and -not $e.licenceText -and -not $mitHolders.Contains($holder)) { $mitHolders.Add($holder) }
    if ($e.licenceFile) { $licenceFiles["$($p.Id) $($p.Version)"] = Join-Path $dir $e.licenceFile }
    if ($e.licenceText) {
        $heading = "$($p.Id) $($p.Version)" + $(if ($e.nativeSource) { ": $($e.nativeSource)" } else { '' })
        $licenceFiles[$heading] = Join-Path $repo $e.licenceText
    }
    if ($e.notices) { $noticeFiles["$($p.Id) $($p.Version)"] = Join-Path $dir $e.notices }
}
foreach ($r in $inventory.runtimePacks) {
    $version = RuntimePackVersion $r.id
    $dir = PackageDir $r.id $version
    $rows += "| [$($r.name)]($($r.url)) | $version | $($r.licence) | $($r.copyright) | Self-contained: the app carries its own .NET. |"
    if (-not $mitHolders.Contains($r.copyright)) { $mitHolders.Add($r.copyright) }
    if ($r.notices) { $noticeFiles["$($r.name) $version"] = Join-Path $dir $r.notices }
}
foreach ($o in $inventory.other) {
    $notes = (@($o.ships, $o.note, $o.decision) | Where-Object { $_ } | ForEach-Object { $_.TrimEnd('.') }) -join '. '
    $rows += "| $(if ($o.url) { "[$($o.name)]($($o.url))" } else { $o.name }) | $($o.version) | $($o.licence) | $($o.copyright) | $notes |"
    if ($o.licenceText) { $licenceFiles[$o.name] = Join-Path $repo $o.licenceText }
}
$rows | ForEach-Object { Line $_ }

Line
Line '## Downloaded by you, not shipped'
Line
Line 'Settings links to these optional speech engines, models and voices. Pendulum never downloads them itself;'
Line 'you choose them and put them in its Data folder.'
Line
Line '| Component | Licence | Source | Notes |'
Line '|---|---|---|---|'
foreach ($d in $inventory.downloads) { Line "| $($d.name) | $($d.licence) | $($d.source) | $($d.note) |" }
if ($inventory.notOffered) { Line; Line $inventory.notOffered }

Line
Line '## Licence texts'
Line
Line '### MIT License'
Line
Line 'Used by the MIT-licensed components above. Copyright holders:'
Line
foreach ($h in $mitHolders) { Line "- Copyright (c) $h" }
Line
Line '```'
[void]$out.Append((Text (Join-Path $repo 'scripts/licences/MIT.txt')) + $nl)
Line '```'
foreach ($k in $licenceFiles.Keys) {
    Line
    Line "### $k"
    Line
    Line '```'
    [void]$out.Append((Text $licenceFiles[$k]) + $nl)
    Line '```'
}

Line
Line '## Notices that come with the components'
Line
Line 'Some components carry other projects'' work, with their own notices, copied here as they ship.'
$seen = @{}
foreach ($k in $noticeFiles.Keys) {
    $text = Text $noticeFiles[$k]
    $hash = [System.BitConverter]::ToString([System.Security.Cryptography.SHA256]::HashData([System.Text.Encoding]::UTF8.GetBytes($text)))
    Line
    Line "### $k"
    Line
    if ($seen.ContainsKey($hash)) { Line "The same notices as $($seen[$hash]), above."; continue }
    $seen[$hash] = $k
    Line '```'
    [void]$out.Append($text + $nl)
    Line '```'
}

$generated = $out.ToString()

if ($Check) {
    $current = if (Test-Path $outputPath) { (Get-Content $outputPath -Raw) -replace "`r`n", "`n" } else { '' }
    if ($current -ne $generated) { Fail 'THIRD-PARTY-NOTICES.md is stale: run pwsh scripts/third-party-notices.ps1 and commit it.' }
    Write-Host 'THIRD-PARTY-NOTICES.md is up to date.'
    exit 0
}

[System.IO.File]::WriteAllText($outputPath, $generated, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $outputPath ($($shipped.Count) packages, $($inventory.runtimePacks.Count) runtime packs, $($inventory.other.Count) other parts)."
